function indent(block: string, by: string): string {
  return block.replace(/\n/g, `\n${by}`);
}

/** The Resources block. `provider` adds the function file and the provider strings. */
function resources(page: (name: string) => string, provider: boolean): string {
  return `<Resources>
  <bt:Images>
    <bt:Image id="Icon.16x16" DefaultValue="${page('assets/icon-16.png')}"/>
    <bt:Image id="Icon.32x32" DefaultValue="${page('assets/icon-32.png')}"/>
    <bt:Image id="Icon.80x80" DefaultValue="${page('assets/icon-80.png')}"/>
  </bt:Images>
  <bt:Urls>
    <bt:Url id="Taskpane.Url" DefaultValue="${page('taskpane.html')}"/>${provider ? `
    <bt:Url id="Commands.Url" DefaultValue="${page('commands.html')}"/>` : ''}
  </bt:Urls>
  <bt:ShortStrings>
    <bt:String id="Group.Label" DefaultValue="${LABEL}"/>
    <bt:String id="ArmButton.Label" DefaultValue="${LABEL}"/>${provider ? `
    <bt:String id="Provider.Name" DefaultValue="${LABEL}"/>
    <bt:String id="Provider.Label" DefaultValue="Teams-møde med referat"/>` : ''}
  </bt:ShortStrings>
  <bt:LongStrings>
    <bt:String id="ArmButton.Tooltip" DefaultValue="Slå OS2taletiltekst til for mødet, så der kommer et referat ud af det."/>${provider ? `
    <bt:String id="Provider.Tooltip" DefaultValue="Opret et Teams-møde, der optages og transskriberes, så OS2taletiltekst kan lave et referat."/>` : ''}
  </bt:LongStrings>
</Resources>`;
}

/**
 * `origin` must be the https origin the add-in is served from, e.g.
 * https://taletiltekst.syddjurs.dk. Throws on anything else: Outlook loads
 * add-ins over https only, and a path or query would end up in every URL.
 */
export function buildManifest(origin: string): string {
  const url = new URL(origin);
  if (url.protocol !== 'https:' || url.pathname !== '/' || url.search || url.hash) {
    throw new Error(`The add-in needs a bare https origin, got ${origin}`);
  }
  const base = xmlEscape(url.origin);
  const page = (name: string) => `${base}${ADDIN_PATH}/${name}`;

  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  OS2taletiltekst for Outlook. Generated by ${base}${ADDIN_PATH}/manifest.xml.
  Permissions: ReadWriteItem, the lowest level that covers it: reading the
  meeting's text, writing the Teams link into the invitation (the meeting-
  provider button), and its own per-meeting note (custom properties). Sign-in is
  nested app authentication, which needs no manifest permission.
-->
<OfficeApp
  xmlns="http://schemas.microsoft.com/office/appforoffice/1.1"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xmlns:bt="http://schemas.microsoft.com/office/officeappbasictypes/1.0"
  xmlns:mailappor="http://schemas.microsoft.com/office/mailappversionoverrides/1.0"
  xsi:type="MailApp">
  <Id>${ADDIN_ID}</Id>
  <Version>${ADDIN_VERSION}</Version>
  <ProviderName>OS2taletiltekst</ProviderName>
  <DefaultLocale>da-DK</DefaultLocale>
  <DisplayName DefaultValue="${LABEL}"/>
  <Description DefaultValue="Slår OS2taletiltekst til for et Teams-møde, så der kommer et referat ud af mødet."/>
  <IconUrl DefaultValue="${page('assets/icon-64.png')}"/>
  <HighResolutionIconUrl DefaultValue="${page('assets/icon-128.png')}"/>
  <SupportUrl DefaultValue="${base}/"/>
  <AppDomains>
    <AppDomain>${base}</AppDomain>
  </AppDomains>
  <Hosts>
    <Host Name="Mailbox"/>
  </Hosts>
  <Requirements>
    <Sets>
      <Set Name="Mailbox" MinVersion="1.3"/>
    </Sets>
  </Requirements>
  <FormSettings>
    <Form xsi:type="ItemEdit">
      <DesktopSettings>
        <SourceLocation DefaultValue="${page('taskpane.html')}"/>
      </DesktopSettings>
    </Form>
  </FormSettings>
  <Permissions>ReadWriteItem</Permissions>
  <Rule xsi:type="RuleCollection" Mode="Or">
    <Rule xsi:type="ItemIs" ItemType="Appointment" FormType="Edit"/>
  </Rule>
  <DisableEntityHighlighting>false</DisableEntityHighlighting>

  <!-- Older clients: the pane button only. -->
  <VersionOverrides xmlns="http://schemas.microsoft.com/office/mailappversionoverrides" xsi:type="VersionOverridesV1_0">
    <Requirements>
      <bt:Sets DefaultMinVersion="1.3">
        <bt:Set Name="Mailbox"/>
      </bt:Sets>
    </Requirements>
    <Hosts>
      <Host xsi:type="MailHost">
        <DesktopFormFactor>
          <ExtensionPoint xsi:type="AppointmentOrganizerCommandSurface">
            <OfficeTab id="TabDefault">
              <Group id="os2taletiltekst.group">
                <Label resid="Group.Label"/>
                ${indent(PANE_BUTTON, '                ')}
              </Group>
            </OfficeTab>
          </ExtensionPoint>
        </DesktopFormFactor>
      </Host>
    </Hosts>
    ${indent(resources(page, false), '    ')}

    <!-- Current clients: the online-meeting provider command next to the pane
         button (a task pane is not a function command). -->
    <VersionOverrides xmlns="http://schemas.microsoft.com/office/mailappversionoverrides/1.1" xsi:type="VersionOverridesV1_1">
      <Description resid="Provider.Name"/>
      <Requirements>
        <bt:Sets DefaultMinVersion="1.3">
          <bt:Set Name="Mailbox"/>
        </bt:Sets>
      </Requirements>
      <Hosts>
        <Host xsi:type="MailHost">
          <DesktopFormFactor>
            <FunctionFile resid="Commands.Url"/>
            <ExtensionPoint xsi:type="AppointmentOrganizerCommandSurface">
              <OfficeTab id="TabDefault">
                <Group id="os2taletiltekst.providerGroup">
                  <Label resid="Provider.Name"/>
                  ${indent(PROVIDER_BUTTON, '                  ')}
                </Group>
                <Group id="os2taletiltekst.group">
                  <Label resid="Group.Label"/>
                  ${indent(PANE_BUTTON, '                  ')}
                </Group>
              </OfficeTab>
            </ExtensionPoint>
          </DesktopFormFactor>
        </Host>
      </Hosts>
      ${indent(resources(page, true), '      ')}
    </VersionOverrides>
  </VersionOverrides>
</OfficeApp>
`;
}
